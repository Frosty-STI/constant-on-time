#!/usr/bin/env python3
"""Generate an inspectable 2..8-phase educational COT PSpice deck.

The generated architecture uses either fixed eligibility windows or deliberately
free-running phase requests. It does not claim to reproduce a commercial
multiphase controller. Run from the repository root.
"""

from __future__ import annotations

import argparse
from pathlib import Path


def engineering(value: float) -> str:
    """Format positive SI values with SPICE-friendly engineering suffixes."""
    scales = ((1e-3, "m"), (1e-6, "u"), (1e-9, "n"), (1e-12, "p"))
    for scale, suffix in scales:
        scaled = value / scale
        if 1 <= abs(scaled) < 1000:
            return f"{scaled:.9g}{suffix}"
    return f"{value:.9g}"


def permit_source(index: int, phases: int, period: float, width_fraction: float) -> str:
    spacing = period / phases
    delay = index * spacing
    width = spacing * width_fraction
    if index == 0:
        low_width = period - width - 2e-9
        return (
            f"VPERMIT1 PERMIT1 0 PULSE(1 0 {engineering(width)} 1n 1n "
            f"{engineering(low_width)} {engineering(period)})"
        )
    return (
        f"VPERMIT{index + 1} PERMIT{index + 1} 0 PULSE(0 1 "
        f"{engineering(delay)} 1n 1n {engineering(width)} {engineering(period)})"
    )


def generate(args: argparse.Namespace) -> str:
    n = args.phases
    period = 1.0 / args.frequency
    ton = period * args.vout / args.vin
    lines = [
        f"Constant On-Time Lab -- generated {n}-phase {args.scheduler} COT deck",
        "* Generated by pspice/scripts/generate_multiphase.py.",
        "* Educational behavioral architecture; not a commercial-controller model.",
        '.INC "pspice/lib/BUCK_PHASE.lib"',
        '.INC "pspice/lib/COT_ONESHOT.lib"',
        '.INC "pspice/lib/COT_CONTROLLER.lib"',
        f".PARAM VIN_DC={args.vin:.9g} VREF_DC={args.vout:.9g}",
        f".PARAM TPER={engineering(period)} TON={engineering(ton)}",
        "VIN IN 0 {VIN_DC}",
        "VREF REF 0 PWL(0 0 5u 0 6u {VREF_DC})",
        "VRIPPLE RIPPLE 0 0",
        f"VILIM ILIM 0 {args.current_limit:.9g}",
        "XCMP OUT REF RIPPLE REQCOMMON COT_REQUEST PARAMS:",
        "+ VLOGIC=5 VSOFT=2m VHYST=4m TDELAY=10n",
    ]

    if args.scheduler == "fixed-window":
        lines.extend(
            permit_source(i, n, period, args.window_fraction) for i in range(n)
        )
        lines.append("* Windows serialize requests, but phase power pulses may overlap.")
    else:
        lines.append("* Free-running requests intentionally expose collision behavior.")

    for i in range(1, n + 1):
        request = (
            f"EREQ{i} REQ{i} 0 VALUE={{V(REQCOMMON)*V(PERMIT{i})}}"
            if args.scheduler == "fixed-window"
            else f"EREQ{i} REQ{i} 0 VALUE={{V(REQCOMMON)}}"
        )
        mismatch_position = i - (n + 1) / 2
        l_value = args.inductance * (
            1 + mismatch_position * args.l_mismatch_pct / 100
        )
        dcr_value = args.dcr * (
            1 - mismatch_position * args.dcr_mismatch_pct / 100
        )
        lines.extend(
            [
                request,
                f"XCL{i} IMON{i} ILIM TRIP{i} COT_CURRENT_LIMIT PARAMS: VLOGIC=5",
                f"XSHOT{i} REQ{i} TRIP{i} GATE{i} READY{i} COT_ONESHOT PARAMS:",
                "+ TON={TON} TOFFMIN=100n VLOGIC=5",
                f"XDRV{i} GATE{i} GH{i} GL{i} COMPLEMENTARY_DRIVER PARAMS:",
                "+ VLOGIC=5 DEAD=20n",
                f"XPH{i} IN OUT GH{i} GL{i} SW{i} IMON{i} BUCK_PHASE PARAMS:",
                f"+ LPH={engineering(l_value)} DCR={engineering(dcr_value)} "
                "RHS=15m RLS=8m",
            ]
        )

    sum_expression = "+".join(f"V(IMON{i})" for i in range(1, n + 1))
    probe_currents = " ".join(f"V(IMON{i})" for i in range(1, n + 1))
    probe_switches = " ".join(f"V(SW{i})" for i in range(1, n + 1))
    probe_gates = " ".join(f"V(GATE{i})" for i in range(1, n + 1))
    lines.extend(
        [
            f"EISUM ISUM 0 VALUE={{{sum_expression}}}",
            f"RESR OUT NCAP {engineering(args.esr)}",
            f"COUT NCAP 0 {engineering(args.capacitance)} IC=0",
            "* Resistive equivalent draws the requested load at target VOUT",
            f"RLOAD OUT 0 {engineering(args.vout / args.load)}",
            "RBLEED OUT 0 100",
            ".IC V(OUT)=0",
            ".OPTIONS RELTOL=1m ABSTOL=10n VNTOL=1u ITL4=2500",
            f".TRAN 5n {engineering(args.stop_time)} 0 5n",
            f".MEAS TRAN VOUT_AVG AVG V(OUT) FROM={engineering(args.stop_time * .9)} "
            f"TO={engineering(args.stop_time)}",
            f".MEAS TRAN ISUM_AVG AVG V(ISUM) FROM={engineering(args.stop_time * .9)} "
            f"TO={engineering(args.stop_time)}",
            f".PROBE V(OUT) V(ISUM) {probe_currents}",
            f"+ {probe_switches}",
            f"+ {probe_gates}",
            ".END",
            "",
        ]
    )
    return "\n".join(lines)


def parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--phases", type=int, default=4, choices=range(2, 9))
    p.add_argument(
        "--scheduler",
        choices=("fixed-window", "free-running"),
        default="fixed-window",
    )
    p.add_argument("--frequency", type=float, default=500e3, help="nominal Hz")
    p.add_argument("--vin", type=float, default=12.0)
    p.add_argument("--vout", type=float, default=5.0)
    p.add_argument(
        "--load",
        type=float,
        default=16.0,
        help="target current in A; emitted as VOUT/load resistance",
    )
    p.add_argument("--inductance", type=float, default=2e-6, help="nominal H")
    p.add_argument("--dcr", type=float, default=10e-3, help="nominal ohm")
    p.add_argument("--capacitance", type=float, default=470e-6, help="F")
    p.add_argument("--esr", type=float, default=5e-3, help="ohm")
    p.add_argument("--current-limit", type=float, default=6.0, help="A/phase")
    p.add_argument("--l-mismatch-pct", type=float, default=0.0)
    p.add_argument("--dcr-mismatch-pct", type=float, default=0.0)
    p.add_argument("--window-fraction", type=float, default=0.7)
    p.add_argument("--stop-time", type=float, default=2e-3)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--force", action="store_true")
    return p


def main() -> int:
    args = parser().parse_args()
    if not 0.1 <= args.window_fraction <= 0.9:
        raise SystemExit("--window-fraction must be between 0.1 and 0.9")
    if not args.vin > args.vout > 0:
        raise SystemExit("require VIN>VOUT>0")
    if min(
        args.frequency,
        args.inductance,
        args.dcr,
        args.capacitance,
        args.esr,
        args.load,
        args.current_limit,
        args.stop_time,
    ) <= 0:
        raise SystemExit("require positive frequency/L/DCR/C/ESR/load/limit/stop-time")
    positions = [i - (args.phases + 1) / 2 for i in range(1, args.phases + 1)]
    if min(1 + p * args.l_mismatch_pct / 100 for p in positions) <= 0:
        raise SystemExit("L mismatch would create a zero or negative phase inductance")
    if min(1 - p * args.dcr_mismatch_pct / 100 for p in positions) <= 0:
        raise SystemExit("DCR mismatch would create a zero or negative phase DCR")
    spacing = 1 / args.frequency / args.phases
    if args.scheduler == "fixed-window" and spacing * (
        1 - args.window_fraction
    ) <= 2e-9:
        raise SystemExit("fixed windows need more than 2 ns separation")
    if args.output.exists() and not args.force:
        raise SystemExit(f"refusing to overwrite {args.output}; add --force")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generate(args), encoding="utf-8")
    print(f"wrote {args.output} ({args.phases} phases, {args.scheduler})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
